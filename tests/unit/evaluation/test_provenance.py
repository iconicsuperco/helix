"""Verify evaluation datasets hard-fail when bytes are absent or drift."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest

from evaluation.config import DatasetTargetConfig
from evaluation.provenance import validate_dataset


def _raw_target(tmp_path: Path, content: bytes) -> DatasetTargetConfig:
    data_path = tmp_path / "dataset.txt"
    data_path.write_bytes(content)
    manifest_path = tmp_path / "manifest.json"
    manifest = {
        "dataset_id": "synthetic-evaluation-fixture",
        "display_name": "Synthetic evaluation fixture",
        "current_version": "fixture-v1",
        "canonical_source": {
            "url": "https://example.invalid/synthetic-fixture.txt",
            "selection_rationale": "Synthetic unit-test fixture only.",
            "retrieved_at": "2026-07-20T00:00:00Z",
            "retrieval_method": "Generated by the unit test.",
        },
        "raw": {
            "expected_path": str(data_path),
            "encoding": "utf-8",
            "version": "fixture-v1",
            "sha256": hashlib.sha256(content).hexdigest(),
            "gitignored": True,
        },
        "license": "Synthetic unit-test fixture.",
        "processed": [],
        "fallback_sources": [],
    }
    manifest_path.write_text(json.dumps(manifest), encoding="utf-8")
    return DatasetTargetConfig(
        label="out_of_corpus",
        manifest_path=manifest_path,
        text_path=data_path,
        artifact="raw",
        artifact_name=None,
    )


def test_valid_dataset_checksum_succeeds(tmp_path: Path) -> None:
    target = _raw_target(tmp_path, b"stable evaluation bytes\n")

    validated = validate_dataset(target)

    assert validated.dataset_id == "synthetic-evaluation-fixture"
    assert validated.version == "fixture-v1"


def test_missing_dataset_hard_fails(tmp_path: Path) -> None:
    target = _raw_target(tmp_path, b"stable evaluation bytes\n")
    target.text_path.unlink()

    with pytest.raises(FileNotFoundError, match="Evaluation dataset does not exist"):
        validate_dataset(target)


def test_checksum_mismatch_hard_fails(tmp_path: Path) -> None:
    target = _raw_target(tmp_path, b"stable evaluation bytes\n")
    target.text_path.write_bytes(b"drifted evaluation bytes\n")

    with pytest.raises(ValueError, match="Evaluation dataset checksum mismatch"):
        validate_dataset(target)
